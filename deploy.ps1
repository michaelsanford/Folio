<#
.SYNOPSIS
    Build and deploy the Folio serverless application with AWS SAM, or roll the live alias back.

.DESCRIPTION
    Validates prerequisites and parameters, builds the ARM64 container image with Docker BuildKit
    (attestations disabled for Lambda manifest compatibility), deploys the CloudFormation stack
    (CloudFront + Lambda Function URL + S3 vault + optional Cognito), applies an ECR lifecycle
    policy to the image repository, and optionally invites an owner or household user in the
    invite-only Cognito User Pool.

    Settings persist per environment. The merged CloudFormation parameter overrides, stack name
    and region are written to samconfig.toml under [<Environment>.deploy.parameters] and the
    deploy runs with `sam deploy --config-env <Environment>`. A later deploy of the same
    environment only needs the parameters that change: anything not passed keeps its stored
    value (pass a parameter explicitly, e.g. -AlarmEmail '' or -EnableBedrock:$false, to change
    or clear it). samconfig.toml holds the master passphrase bcrypt hash when one is set, so it
    must stay out of version control (the script warns when git does not ignore it). If the
    deploy fails, samconfig.toml is restored to its previous content.

    Session and origin-verify secrets are generated by CloudFormation in AWS Secrets Manager;
    no secret is generated or passed on the command line.

    After a successful deploy the script reads the function's ImageUri, derives the ECR
    repository and applies a lifecycle policy: untagged images expire after 1 day and only the
    5 most recent images are kept (this is also the rollback window).

    -RollbackToVersion lists the published Lambda versions, points the "live" alias (which the
    Function URL and therefore CloudFront serve) at the chosen version, and exits without
    building or deploying. The next deploy publishes a new version and moves the alias forward
    again. A version carries its own environment variables and settings as well as its image.

    Supports -WhatIf and -Confirm.

.PARAMETER Region
    AWS region. Defaults to the stored value for the environment, else ca-central-1.

.PARAMETER StackName
    CloudFormation stack name. Defaults to the stored value for the environment, else
    folio-<Environment>.

.PARAMETER Environment
    Stage name (lowercase letters, digits, hyphens; 1-21 chars). Selects the samconfig.toml
    config environment and names the vault bucket, user pool and log group.

.PARAMETER MasterPassword
    Master passphrase. It is hashed locally with bcrypt; only the hash is sent to
    CloudFormation (MasterPasswordHash). Required the first time with -DisableCognito.

.PARAMETER AllowedOrigin
    Optional extra origin allowed to call the API cross-origin. Leave empty: the PWA and API are
    both served from the CloudFront URL, which needs no CORS.

.PARAMETER ReservedConcurrency
    Optional Lambda reserved concurrency (spend cap). 0 = unreserved (required on accounts whose
    concurrency quota is 10). The app is safe with several instances (S3 conditional writes).

.PARAMETER ExistingVaultBucket
    Name of a retained S3 vault bucket to reuse instead of creating a new one.

.PARAMETER OwnerEmail
    Email address to invite in the Cognito User Pool (idempotent). Not valid with Cognito
    disabled.

.PARAMETER DisableCognito
    Deploy in single Master Passphrase mode instead of Cognito. Requires a master passphrase
    (-MasterPassword now, or a hash stored from an earlier deploy). -DisableCognito:$false
    re-enables Cognito.

.PARAMETER EnableBedrock
    Enable Amazon Bedrock auto-classification. -EnableBedrock:$false disables it.

.PARAMETER BedrockModelId
    Bedrock model ID or inference profile ID (template default amazon.nova-micro-v1:0).

.PARAMETER AlarmEmail
    Email for CloudWatch alarm (SNS) and AWS Budgets notifications. Confirm the SNS subscription
    from the email AWS sends. Pass '' to remove notifications.

.PARAMETER MonthlyBudgetUsd
    Monthly account-wide AWS cost budget in USD (template default 5). Needs -AlarmEmail.

.PARAMETER RollbackToVersion
    Point the "live" alias at this published Lambda version number and exit.

.EXAMPLE
    .\deploy.ps1 -Region ca-central-1 -StackName folio-prod -OwnerEmail you@example.com -AlarmEmail you@example.com

.EXAMPLE
    .\deploy.ps1 -Environment qa -StackName Folio-QA -ExistingVaultBucket folio-vault-qa-012345678901-ca-central-1

.EXAMPLE
    .\deploy.ps1 -Environment qa -StackName Folio-QA -DisableCognito -MasterPassword (Read-Host -AsSecureString)

.EXAMPLE
    .\deploy.ps1 -Environment prod -EnableBedrock -BedrockModelId us.amazon.nova-micro-v1:0

.EXAMPLE
    .\deploy.ps1 -Environment prod -RollbackToVersion 7

.EXAMPLE
    .\deploy.ps1 -Environment prod -WhatIf
#>
[CmdletBinding(SupportsShouldProcess)]
param (
    [string]$Region = "ca-central-1",
    [string]$StackName = "",
    [string]$Environment = "prod",
    [securestring]$MasterPassword,
    [string]$AllowedOrigin = "",
    [ValidateRange(0, 1000)]
    [int]$ReservedConcurrency = 0,
    [string]$ExistingVaultBucket = "",
    [string]$OwnerEmail = "",
    [switch]$DisableCognito,
    [switch]$EnableBedrock,
    [string]$BedrockModelId = "",
    [string]$AlarmEmail = "",
    [ValidateRange(1, 100000)]
    [int]$MonthlyBudgetUsd = 5,
    [ValidateRange(1, [int]::MaxValue)]
    [int]$RollbackToVersion
)

$ErrorActionPreference = "Stop"

$SamConfigPath = Join-Path $PSScriptRoot "samconfig.toml"
# Template parameters removed in favour of Secrets Manager; dropped from stored settings.
$ObsoleteParameters = @("SessionSecretKey", "OriginVerifySecret")

function ConvertFrom-TomlString {
    param ([string]$Raw)
    $v = $Raw.Trim()
    if ($v.Length -ge 2 -and $v.StartsWith('"') -and $v.EndsWith('"')) {
        $v = $v.Substring(1, $v.Length - 2)
        return [regex]::Replace($v, '\\(["\\])', '$1')
    }
    return $v
}

function ConvertTo-TomlString {
    param ([string]$Value)
    return '"' + $Value.Replace('\', '\\').Replace('"', '\"') + '"'
}

function Get-SamConfigSection {
    # Returns @{ Settings = ordered map of key -> raw value; Overrides = ordered map } for [<env>.deploy.parameters].
    param ([string]$Path, [string]$ConfigEnv)

    $settings = [ordered]@{}
    $overrides = [ordered]@{}
    if (-not (Test-Path $Path)) {
        return @{ Settings = $settings; Overrides = $overrides }
    }

    $header = "[$ConfigEnv.deploy.parameters]"
    $inSection = $false
    foreach ($line in Get-Content -Path $Path) {
        $trim = $line.Trim()
        if ($trim.StartsWith("[")) {
            $inSection = ($trim -eq $header)
            continue
        }
        if (-not $inSection -or -not $trim -or $trim.StartsWith("#")) { continue }
        $m = [regex]::Match($trim, '^([A-Za-z0-9_]+)\s*=\s*(.*)$')
        if ($m.Success) {
            $settings[$m.Groups[1].Value] = $m.Groups[2].Value
        }
    }

    if ($settings.Contains("parameter_overrides")) {
        $raw = ConvertFrom-TomlString $settings["parameter_overrides"]
        foreach ($pm in [regex]::Matches($raw, '([A-Za-z0-9]+)=(?:"((?:[^"\\]|\\.)*)"|(\S*))')) {
            $val = if ($pm.Groups[2].Success) { [regex]::Replace($pm.Groups[2].Value, '\\(["\\])', '$1') } else { $pm.Groups[3].Value }
            $overrides[$pm.Groups[1].Value] = $val
        }
    }
    return @{ Settings = $settings; Overrides = $overrides }
}

function Write-SamConfigSection {
    # Replaces (or appends) [<env>.deploy.parameters] and leaves every other section untouched.
    param ([string]$Path, [string]$ConfigEnv, [string[]]$BodyLines)

    $header = "[$ConfigEnv.deploy.parameters]"
    $existing = if (Test-Path $Path) { @(Get-Content -Path $Path) } else { @("version = 0.1") }
    $out = New-Object System.Collections.Generic.List[string]
    $skipping = $false
    $written = $false
    foreach ($line in $existing) {
        $trim = $line.Trim()
        if ($trim.StartsWith("[")) {
            if ($skipping) { $skipping = $false }
            if ($trim -eq $header) {
                $skipping = $true
                $out.Add($header)
                foreach ($b in $BodyLines) { $out.Add($b) }
                $out.Add("")
                $written = $true
                continue
            }
        }
        if (-not $skipping) { $out.Add($line) }
    }
    if (-not $written) {
        if ($out.Count -gt 0 -and $out[$out.Count - 1].Trim()) { $out.Add("") }
        $out.Add($header)
        foreach ($b in $BodyLines) { $out.Add($b) }
    }
    [System.IO.File]::WriteAllText($Path, (($out -join "`n").TrimEnd() + "`n"), (New-Object System.Text.UTF8Encoding($false)))
}

function Get-StackOutputMap {
    param ([string]$Name, [string]$AwsRegion)
    $raw = aws cloudformation describe-stacks --stack-name "$Name" --region "$AwsRegion" --query "Stacks[0].Outputs" --output json
    if ($LASTEXITCODE -ne 0) {
        throw "Failed to retrieve CloudFormation stack outputs for $Name."
    }
    $map = @{}
    if ($raw) {
        foreach ($item in @($raw | ConvertFrom-Json)) {
            if ($item.OutputKey) { $map[$item.OutputKey] = $item.OutputValue }
        }
    }
    return $map
}

function Get-EcrRepositoryFromImageUri {
    # 123456789012.dkr.ecr.ca-central-1.amazonaws.com/repo/name@sha256:abc  -> repo/name
    # 123456789012.dkr.ecr.ca-central-1.amazonaws.com/repo/name:tag         -> repo/name
    param ([string]$ImageUri)
    $slash = $ImageUri.IndexOf('/')
    if ($slash -lt 0) { return $null }
    $path = $ImageUri.Substring($slash + 1)
    $at = $path.IndexOf('@')
    if ($at -ge 0) { return $path.Substring(0, $at) }
    $colon = $path.LastIndexOf(':')
    if ($colon -gt $path.LastIndexOf('/')) { return $path.Substring(0, $colon) }
    return $path
}

$Environment = $Environment.Trim().ToLowerInvariant()
if ($Environment -notmatch '^[a-z0-9][a-z0-9-]{0,20}$') {
    throw "Environment must be lowercase alphanumeric/hyphens (1-21 chars) for valid S3 bucket naming."
}

$Stored = Get-SamConfigSection -Path $SamConfigPath -ConfigEnv $Environment
if (-not $PSBoundParameters.ContainsKey("Region") -and $Stored.Settings.Contains("region")) {
    $Region = ConvertFrom-TomlString $Stored.Settings["region"]
}
if (-not $StackName.Trim()) {
    $StackName = if ($Stored.Settings.Contains("stack_name")) { ConvertFrom-TomlString $Stored.Settings["stack_name"] } else { "folio-$Environment" }
}
$StackName = $StackName.Trim()

if (-not (Get-Command aws -ErrorAction SilentlyContinue)) {
    throw "AWS CLI is not installed or not in PATH."
}

# ---------------------------------------------------------------------------
# Rollback mode: move the "live" alias and exit.
# ---------------------------------------------------------------------------
if ($PSBoundParameters.ContainsKey("RollbackToVersion")) {
    Write-Host "==========================================" -ForegroundColor Cyan
    Write-Host "Folio - Roll back live alias" -ForegroundColor Cyan
    Write-Host "Region: $Region | Stack: $StackName" -ForegroundColor Cyan
    Write-Host "==========================================" -ForegroundColor Cyan

    $Outputs = Get-StackOutputMap -Name $StackName -AwsRegion $Region
    $FunctionName = $Outputs["FunctionName"]
    if (-not $FunctionName) {
        $FunctionName = (aws cloudformation describe-stack-resource --stack-name "$StackName" --region "$Region" `
                --logical-resource-id FolioServerlessFunction --query "StackResourceDetail.PhysicalResourceId" --output text)
        if ($LASTEXITCODE -ne 0 -or -not $FunctionName) { throw "Could not find the Folio function in stack '$StackName'." }
        $FunctionName = $FunctionName.Trim()
    }

    $VersionsRaw = aws lambda list-versions-by-function --function-name "$FunctionName" --region "$Region" --output json
    if ($LASTEXITCODE -ne 0) { throw "Failed to list versions of '$FunctionName'." }
    $Versions = @(($VersionsRaw | ConvertFrom-Json).Versions | Where-Object { $_.Version -ne '$LATEST' })

    $AliasRaw = aws lambda get-alias --function-name "$FunctionName" --name live --region "$Region" --output json
    if ($LASTEXITCODE -ne 0) { throw "Function '$FunctionName' has no 'live' alias (deploy once with this template first)." }
    $CurrentVersion = ($AliasRaw | ConvertFrom-Json).FunctionVersion

    Write-Host "`nPublished versions of ${FunctionName}:" -ForegroundColor Yellow
    $Versions |
        Sort-Object { [int]$_.Version } |
        Select-Object @{ n = "Version"; e = { $_.Version } },
                      @{ n = "Live"; e = { if ($_.Version -eq $CurrentVersion) { "<- live" } else { "" } } },
                      @{ n = "LastModified"; e = { $_.LastModified } },
                      @{ n = "CodeSha256"; e = { $_.CodeSha256.Substring(0, [Math]::Min(12, $_.CodeSha256.Length)) } } |
        Format-Table -AutoSize | Out-Host

    $Target = "$RollbackToVersion"
    if (-not ($Versions | Where-Object { $_.Version -eq $Target })) {
        throw "Version $Target does not exist for '$FunctionName'. Choose one of the versions listed above."
    }
    if ($Target -eq $CurrentVersion) {
        Write-Host "Alias 'live' already points at version $Target. Nothing to do." -ForegroundColor Green
        exit 0
    }

    if ($PSCmdlet.ShouldProcess("$FunctionName alias 'live' (currently version $CurrentVersion)", "Point at version $Target")) {
        aws lambda update-alias --function-name "$FunctionName" --name live --function-version "$Target" --region "$Region" --output json | Out-Null
        if ($LASTEXITCODE -ne 0) { throw "Failed to update alias 'live' to version $Target." }
        Write-Host "Alias 'live' now serves version $Target (was $CurrentVersion)." -ForegroundColor Green
        Write-Host "Undo: .\deploy.ps1 -Environment $Environment -RollbackToVersion $CurrentVersion" -ForegroundColor DarkGray
        Write-Host "The next deploy publishes a new version and moves 'live' forward again." -ForegroundColor DarkGray
    }
    exit 0
}

# ---------------------------------------------------------------------------
# Deploy mode: merge stored settings with the parameters passed now.
# ---------------------------------------------------------------------------
$Overrides = [ordered]@{}
foreach ($k in $Stored.Overrides.Keys) {
    if ($ObsoleteParameters -notcontains $k) { $Overrides[$k] = $Stored.Overrides[$k] }
}
foreach ($k in $ObsoleteParameters) {
    if ($Stored.Overrides.Contains($k)) {
        Write-Host "Dropping obsolete stored parameter '$k' (now generated in AWS Secrets Manager)." -ForegroundColor DarkYellow
    }
}
$Overrides["EnvironmentName"] = $Environment

if ($PSBoundParameters.ContainsKey("DisableCognito")) {
    $Overrides["EnableCognito"] = if ($DisableCognito) { "false" } else { "true" }
} elseif (-not $Overrides.Contains("EnableCognito")) {
    $Overrides["EnableCognito"] = "true"
}
if ($PSBoundParameters.ContainsKey("AllowedOrigin")) { $Overrides["AllowedOrigin"] = $AllowedOrigin.Trim() }
if ($PSBoundParameters.ContainsKey("ReservedConcurrency")) { $Overrides["ReservedConcurrency"] = "$ReservedConcurrency" }
if ($PSBoundParameters.ContainsKey("ExistingVaultBucket")) { $Overrides["ExistingVaultBucketName"] = $ExistingVaultBucket.Trim() }
if ($PSBoundParameters.ContainsKey("EnableBedrock")) { $Overrides["EnableBedrock"] = if ($EnableBedrock) { "true" } else { "false" } }
if ($PSBoundParameters.ContainsKey("BedrockModelId")) { $Overrides["BedrockModelId"] = $BedrockModelId.Trim() }
if ($PSBoundParameters.ContainsKey("AlarmEmail")) { $Overrides["AlarmEmail"] = $AlarmEmail.Trim().ToLowerInvariant() }
if ($PSBoundParameters.ContainsKey("MonthlyBudgetUsd")) { $Overrides["MonthlyBudgetUsd"] = "$MonthlyBudgetUsd" }

# Empty values are dropped so the template default applies.
foreach ($k in @($Overrides.Keys)) {
    if ([string]::IsNullOrEmpty($Overrides[$k])) { $Overrides.Remove($k) }
}

$CognitoEnabled = ($Overrides["EnableCognito"] -ne "false")
$NormalizedOwnerEmail = $OwnerEmail.Trim().ToLowerInvariant()
if (-not $CognitoEnabled -and $NormalizedOwnerEmail) {
    throw "-OwnerEmail cannot be used with Cognito disabled (-DisableCognito, current or stored)."
}
if (-not $CognitoEnabled -and -not $MasterPassword -and -not $Overrides.Contains("MasterPasswordHash")) {
    throw "-DisableCognito requires -MasterPassword so production authentication never falls back to an unconfigured state."
}
if ($NormalizedOwnerEmail -and $NormalizedOwnerEmail -notmatch '^[^@\s]+@[^@\s]+\.[^@\s]+$') {
    throw "OwnerEmail '$OwnerEmail' does not look like a valid email address."
}
if ($Overrides.Contains("AlarmEmail") -and $Overrides["AlarmEmail"] -notmatch '^[^@\s]+@[^@\s]+\.[^@\s]+$') {
    throw "AlarmEmail '$($Overrides["AlarmEmail"])' does not look like a valid email address."
}
if ($Overrides.Contains("MonthlyBudgetUsd") -and -not $Overrides.Contains("AlarmEmail")) {
    Write-Warning "MonthlyBudgetUsd is set but AlarmEmail is empty: the budget is only created when AlarmEmail is set."
}
foreach ($k in $Overrides.Keys) {
    if ($Overrides[$k] -match '["\s]') {
        throw "Parameter '$k' must not contain quotes or whitespace."
    }
}

Write-Host "==========================================" -ForegroundColor Cyan
Write-Host "Folio - AWS SAM Serverless Deployment" -ForegroundColor Cyan
Write-Host "Region: $Region | Stack: $StackName | Environment: $Environment" -ForegroundColor Cyan
Write-Host "==========================================" -ForegroundColor Cyan
Write-Host "Effective parameters (stored in samconfig.toml [$Environment.deploy.parameters]):" -ForegroundColor Gray
foreach ($k in $Overrides.Keys) {
    $shown = if ($k -eq "MasterPasswordHash") { "(bcrypt hash, hidden)" } else { $Overrides[$k] }
    Write-Host ("  {0,-24} {1}" -f $k, $shown) -ForegroundColor Gray
}
if ($MasterPassword) {
    Write-Host ("  {0,-24} {1}" -f "MasterPasswordHash", "(new hash from -MasterPassword)") -ForegroundColor Gray
}

if (-not $PSCmdlet.ShouldProcess("CloudFormation stack '$StackName' in $Region", "Build and deploy Folio")) {
    return
}

# 1. Verify Prerequisites
Write-Host "`n[1/5] Verifying AWS SAM CLI & Docker..." -ForegroundColor Yellow
if (-not (Get-Command sam -ErrorAction SilentlyContinue)) {
    throw "AWS SAM CLI is not installed. Install via: winget install Amazon.SAM-CLI"
}
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    throw "Docker is not installed or not running."
}

$AccountId = (aws sts get-caller-identity --query "Account" --output text)
if ($LASTEXITCODE -ne 0 -or -not $AccountId) {
    throw "AWS authentication failed. Check AWS_PROFILE / credentials."
}
$AccountId = $AccountId.Trim()
Write-Host "Authenticated as AWS Account: $AccountId in $Region" -ForegroundColor Green

if (Get-Command git -ErrorAction SilentlyContinue) {
    & git -C $PSScriptRoot check-ignore -q samconfig.toml 2>$null
    if ($LASTEXITCODE -eq 1) {
        Write-Warning "samconfig.toml is not git-ignored. It stores the MasterPasswordHash and alarm email; add it to .gitignore."
    }
}

if ($MasterPassword) {
    # Hash locally so the passphrase itself never reaches CloudFormation or the
    # Lambda environment, both of which are readable with modest IAM access.
    # Piped over stdin so it never appears in the process list either.
    Write-Host "Hashing master passphrase locally (bcrypt)..." -ForegroundColor Yellow
    $BackendPath = Join-Path $PSScriptRoot "backend"
    $HashScript = Join-Path $BackendPath "scripts\hash_password.py"

    $Plain = [System.Net.NetworkCredential]::new("", $MasterPassword).Password
    if (Get-Command uv -ErrorAction SilentlyContinue) {
        $Hash = ($Plain | & uv run --directory $BackendPath --quiet python $HashScript)
    } else {
        $PythonExe = Join-Path $BackendPath ".venv\Scripts\python.exe"
        if (-not (Test-Path $PythonExe)) { $PythonExe = "python" }
        $Hash = ($Plain | & $PythonExe $HashScript)
    }
    $Plain = $null
    if ($LASTEXITCODE -ne 0 -or -not $Hash) { throw "Failed to hash the master passphrase." }
    $Overrides["MasterPasswordHash"] = "$Hash".Trim()
}

$PrevAttestations = $env:BUILDX_NO_DEFAULT_ATTESTATIONS
$PrevSamConfig = if (Test-Path $SamConfigPath) { [System.IO.File]::ReadAllText($SamConfigPath) } else { $null }
$DeploySucceeded = $false
Push-Location $PSScriptRoot

try {
    # 2. SAM Build
    Write-Host "`n[2/5] Building Serverless Application (SAM)..." -ForegroundColor Yellow
    # Disable OCI provenance attestations so BuildKit emits single-platform manifests Lambda accepts.
    $env:BUILDX_NO_DEFAULT_ATTESTATIONS = "1"
    sam build -t template.yaml --use-buildkit
    if ($LASTEXITCODE -ne 0) {
        throw "SAM build failed with exit code $LASTEXITCODE."
    }

    # 3. SAM Deploy (settings come from samconfig.toml so the hash never hits the process list)
    Write-Host "`n[3/5] Deploying SAM Stack ($StackName)..." -ForegroundColor Yellow
    $OverrideString = ($Overrides.Keys | ForEach-Object { "$_=`"$($Overrides[$_])`"" }) -join " "
    $TagString = "app=`"folio`" env=`"$Environment`""
    Write-SamConfigSection -Path $SamConfigPath -ConfigEnv $Environment -BodyLines @(
        "stack_name = $(ConvertTo-TomlString $StackName)",
        "region = $(ConvertTo-TomlString $Region)",
        "resolve_s3 = true",
        "resolve_image_repos = true",
        "capabilities = `"CAPABILITY_IAM`"",
        "confirm_changeset = false",
        "fail_on_empty_changeset = false",
        "parameter_overrides = $(ConvertTo-TomlString $OverrideString)",
        "tags = $(ConvertTo-TomlString $TagString)"
    )

    sam deploy `
        --config-file "$SamConfigPath" `
        --config-env "$Environment" `
        --tags "app=folio" "env=$Environment"
    if ($LASTEXITCODE -ne 0) {
        throw "SAM deploy failed with exit code $LASTEXITCODE."
    }
    $DeploySucceeded = $true

    $OutputsMap = Get-StackOutputMap -Name $StackName -AwsRegion $Region
    $AppUrl = $OutputsMap["AppUrl"]
    $FunctionName = $OutputsMap["FunctionName"]
    $VaultBucket = $OutputsMap["S3VaultBucket"]
    $UserPoolId = $OutputsMap["CognitoUserPoolId"]
    $ClientId = $OutputsMap["CognitoClientId"]

    # 4. ECR lifecycle policy (untagged after 1 day, keep the 5 most recent images)
    Write-Host "`n[4/5] Applying ECR lifecycle policy..." -ForegroundColor Yellow
    $ImageUri = $null
    if ($FunctionName) {
        $ImageUri = aws lambda get-function --function-name "$FunctionName" --region "$Region" --query "Code.ImageUri" --output text
        if ($LASTEXITCODE -ne 0) { $ImageUri = $null }
    }
    $RepoName = if ($ImageUri) { Get-EcrRepositoryFromImageUri -ImageUri "$ImageUri".Trim() } else { $null }
    if (-not $RepoName) {
        Write-Warning "Could not determine the ECR repository from the function ImageUri; lifecycle policy not applied."
    } elseif ($PSCmdlet.ShouldProcess("ECR repository '$RepoName'", "Put lifecycle policy")) {
        $Policy = @{
            rules = @(
                @{
                    rulePriority = 1
                    description  = "Expire untagged images after 1 day"
                    selection    = @{ tagStatus = "untagged"; countType = "sinceImagePushed"; countUnit = "days"; countNumber = 1 }
                    action       = @{ type = "expire" }
                },
                @{
                    rulePriority = 2
                    description  = "Keep only the 5 most recent images (rollback window)"
                    selection    = @{ tagStatus = "any"; countType = "imageCountMoreThan"; countNumber = 5 }
                    action       = @{ type = "expire" }
                }
            )
        } | ConvertTo-Json -Depth 6 -Compress
        $PolicyFile = [System.IO.Path]::GetTempFileName()
        try {
            [System.IO.File]::WriteAllText($PolicyFile, $Policy, (New-Object System.Text.UTF8Encoding($false)))
            aws ecr put-lifecycle-policy --repository-name "$RepoName" --region "$Region" `
                --lifecycle-policy-text "file://$PolicyFile" --output json | Out-Null
            if ($LASTEXITCODE -ne 0) {
                Write-Warning "Failed to apply the ECR lifecycle policy to '$RepoName' (deploy itself succeeded)."
            } else {
                Write-Host "ECR lifecycle policy applied to '$RepoName'." -ForegroundColor Green
            }
        } finally {
            Remove-Item $PolicyFile -Force -ErrorAction SilentlyContinue
        }
    }

    # 5. Outputs and optional Cognito invite
    Write-Host "`n[5/5] Deployment Outputs" -ForegroundColor Yellow
    Write-Host "`n========================================================" -ForegroundColor Green
    Write-Host "Folio Serverless SAM Deployment Complete!" -ForegroundColor Green
    Write-Host "Application URL (CloudFront): $AppUrl" -ForegroundColor Cyan
    Write-Host "  (The raw Lambda Function URL rejects direct requests; always use the URL above.)" -ForegroundColor DarkGray
    Write-Host "S3 Storage Vault Bucket:      $VaultBucket" -ForegroundColor Gray
    Write-Host "Lambda Function (alias live): $FunctionName" -ForegroundColor Gray
    Write-Host "Roll back if needed:          .\deploy.ps1 -Environment $Environment -RollbackToVersion <n>" -ForegroundColor DarkGray
    if ($Overrides.Contains("AlarmEmail")) {
        Write-Host "Alarms notify $($Overrides["AlarmEmail"]): confirm the 'AWS Notification - Subscription Confirmation' email" -ForegroundColor Yellow
        Write-Host "  or no alarm emails will be delivered. Budget alerts are emailed directly." -ForegroundColor Yellow
    }
    if ($UserPoolId -and $UserPoolId -ne "None") {
        Write-Host "Cognito User Pool ID:         $UserPoolId" -ForegroundColor Yellow
        Write-Host "Cognito App Client ID:        $ClientId" -ForegroundColor Yellow

        if ($NormalizedOwnerEmail) {
            Write-Host "`nInviting/verifying Cognito user '$NormalizedOwnerEmail'..." -ForegroundColor Yellow
            $prevEap = $ErrorActionPreference
            $ErrorActionPreference = "Continue"
            try {
                $probeRaw = & aws cognito-idp admin-get-user `
                    --user-pool-id "$UserPoolId" `
                    --username "$NormalizedOwnerEmail" `
                    --region "$Region" `
                    --output json 2>&1
                $probeCode = $LASTEXITCODE
            } finally {
                $ErrorActionPreference = $prevEap
            }
            $probeText = ($probeRaw | ForEach-Object { $_.ToString() }) -join "`n"

            if ($probeCode -eq 0) {
                $userObj = $probeText | ConvertFrom-Json
                $userStatus = $userObj.UserStatus
                Write-Host "Cognito user '$NormalizedOwnerEmail' already exists (status: $userStatus) -- skipping invite." -ForegroundColor Gray
                if ($userStatus -eq "FORCE_CHANGE_PASSWORD") {
                    Write-Host "To resend the temporary password email: aws cognito-idp admin-create-user --user-pool-id $UserPoolId --username $NormalizedOwnerEmail --message-action RESEND --desired-delivery-mediums EMAIL --region $Region" -ForegroundColor DarkGray
                }
            } elseif ($probeText -match "UserNotFoundException") {
                if ($PSCmdlet.ShouldProcess("Cognito user pool '$UserPoolId'", "Invite '$NormalizedOwnerEmail'")) {
                    aws cognito-idp admin-create-user `
                        --user-pool-id "$UserPoolId" `
                        --region "$Region" `
                        --username "$NormalizedOwnerEmail" `
                        --user-attributes "Name=email,Value=$NormalizedOwnerEmail" "Name=email_verified,Value=true" `
                        --desired-delivery-mediums EMAIL `
                        --output json | Out-Null
                    if ($LASTEXITCODE -ne 0) {
                        throw "Failed to invite Cognito user '$NormalizedOwnerEmail' in pool '$UserPoolId'."
                    }
                    Write-Host "Invited '$NormalizedOwnerEmail' to Cognito User Pool '$UserPoolId'." -ForegroundColor Green
                    Write-Host "Check email (including spam) for the temporary password from no-reply@verificationemail.com," -ForegroundColor Cyan
                    Write-Host "then visit $AppUrl to choose your permanent passphrase (20+ chars) and scan the TOTP QR code." -ForegroundColor Cyan
                }
            } else {
                throw "Failed to inspect Cognito user '$NormalizedOwnerEmail' in pool '$UserPoolId':`n$probeText"
            }
        } else {
            Write-Host "To invite a user (idempotent): .\deploy.ps1 -Environment $Environment -OwnerEmail you@example.com" -ForegroundColor DarkGray
        }
    } else {
        Write-Host "Authentication Mode:          Master Passphrase (Cognito disabled)" -ForegroundColor Yellow
    }
    Write-Host "========================================================" -ForegroundColor Green
} finally {
    if (-not $DeploySucceeded) {
        # Do not persist settings from a failed deploy.
        if ($null -ne $PrevSamConfig) {
            [System.IO.File]::WriteAllText($SamConfigPath, $PrevSamConfig, (New-Object System.Text.UTF8Encoding($false)))
        } elseif (Test-Path $SamConfigPath) {
            Remove-Item $SamConfigPath -Force -ErrorAction SilentlyContinue
        }
    }
    if ($null -ne $PrevAttestations) {
        $env:BUILDX_NO_DEFAULT_ATTESTATIONS = $PrevAttestations
    } else {
        Remove-Item Env:\BUILDX_NO_DEFAULT_ATTESTATIONS -ErrorAction SilentlyContinue
    }
    Pop-Location
}
